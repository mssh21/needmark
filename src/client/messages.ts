export type ClientMessage = keyof typeof english;

export function uiText(language: NeedMarkLanguage, key: ClientMessage, values: Record<string, string | number> = {}): string {
  const text = language === 'en' ? english[key] ?? key : key;
  return text.replace(/\{([a-z]+)\}/gi, (placeholder, name: string) => String(values[name] ?? placeholder));
}

export function resolveClientLanguage(configured: unknown, preference: unknown): NeedMarkLanguage {
  return isNeedMarkLanguage(preference) ? preference : isNeedMarkLanguage(configured) ? configured : 'ja';
}

